function setup() {
  createCanvas(600, 400);
}

function draw() {
  background(230, 240, 255);

  // 큰 원 3개
  fill(255, 120, 150, 180);
  stroke(200, 50, 100);
  strokeWeight(3);
  ellipse(180, 200, 280, 280);

  fill(120, 200, 255, 180);
  stroke(50, 100, 200);
  ellipse(280, 180, 200, 200);

  fill(180, 255, 150, 180);
  stroke(50, 150, 80);
  ellipse(400, 250, 220, 220);

  // 기울어진 사각형
  push();
  translate(300, 200);
  rotate(PI / 6);
  fill(255, 220, 120, 200);
  stroke(200, 150, 0);
  rect(-100, -50, 200, 100);
  pop();

  // 삼각형 겹치기
  fill(100, 50, 200, 160);
  stroke(60, 0, 150);
  triangle(100, 350, 200, 100, 300, 350);

  fill(255, 100, 200, 140);
  stroke(200, 0, 150);
  triangle(250, 350, 400, 50, 500, 350);

  // 작은 도형 20개 (직접 배치)
  stroke(80);
  fill(255, 200, 200, 180); ellipse(50, 50, 20);
  fill(200, 255, 200, 180); rect(80, 60, 15, 15);
  fill(200, 200, 255, 180); ellipse(120, 80, 25);
  fill(255, 220, 180, 180); rect(160, 90, 20, 20);
  fill(220, 180, 255, 180); ellipse(200, 70, 18);
  fill(180, 255, 220, 180); rect(240, 60, 22, 22);
  fill(255, 180, 220, 180); ellipse(280, 100, 15);
  fill(180, 220, 255, 180); rect(320, 120, 25, 25);
  fill(220, 255, 180, 180); ellipse(360, 140, 20);
  fill(255, 200, 180, 180); rect(400, 160, 18, 18);

  fill(200, 255, 220, 180); ellipse(440, 180, 22);
  fill(180, 200, 255, 180); rect(480, 200, 20, 20);
  fill(255, 220, 200, 180); ellipse(520, 220, 25);
  fill(220, 200, 255, 180); rect(560, 240, 15, 15);
  fill(180, 255, 200, 180); ellipse(100, 300, 20);
  fill(200, 180, 255, 180); rect(150, 320, 22, 22);
  fill(255, 180, 200, 180); ellipse(200, 340, 18);
  fill(180, 220, 255, 180); rect(250, 360, 20, 20);
  fill(220, 255, 180, 180); ellipse(300, 380, 25);
  fill(255, 200, 180, 180); rect(350, 360, 18, 18);
}


